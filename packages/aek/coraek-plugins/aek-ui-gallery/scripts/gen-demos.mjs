#!/usr/bin/env node
// BQ4-4 generator: turns the ported shadcnspace registry (config/registry/components/{index,categories}.ts)
// into a generated TS demo index (src/web/ported/generated/demos.ts).
// Run once; commit the output. Re-run after re-porting.
//
// The registry index.ts is a plain object-literal array (with `categories["x"]` refs); we eval it
// with a categories stub, keep entries whose primary .tsx file lives in the ported tree
// (non-blocks), and emit per-category demo lists whose `key` matches the Vite import.meta.glob
// keys of '../components/shadcn-space/**/*.tsx' (relative to generated/demos.ts).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ported = join(here, '..', 'src/web/ported')

function loadCategories() {
  let text = readFileSync(join(ported, 'config/registry/components/categories.ts'), 'utf8')
  text = text.replace(/^import .*$/m, '').replace('export const categories =', 'categories =').replace(/ as const;/, ';')
  const fn = new Function(`${text}; return categories`)
  return fn()
}

function loadEntries(categories) {
  let text = readFileSync(join(ported, 'config/registry/components/index.ts'), 'utf8')
  text = text.replace(/^import .*$/m, '')
  const start = text.indexOf('export const components = [')
  const end = text.lastIndexOf(']')
  let body = text.slice(start + 'export const components = '.length, end + 1)
  // The array body is JS (string literals, arrays) — evaluate it with a categories stub.
  const fn = new Function('categories', `return ${body}`)
  return fn(categories)
}

const categories = loadCategories()
const entries = loadEntries(categories)

// Primary file of an entry = first .tsx under the ported tree (non-blocks).
const demos = []
const seen = new Set()
for (const e of entries) {
  const tsx = e.files.find((f) => f.path.endsWith('.tsx') && f.path.includes('shadcn-space') && !f.path.includes('shadcn-space/blocks/'))
  if (!tsx) continue
  // key relative to generated/demos.ts, e.g. ../components/shadcn-space/button/button-01.tsx
  const key = './ported/' + txsRelKey(tsx.path)
  if (seen.has(key)) continue
  seen.add(key)
  demos.push({
    key,
    name: e.name,
    title: e.title,
    description: e.description ?? '',
    category: catOf(tsx.path),
    categoryTitle: categories[catOf(tsx.path)]?.title ?? catOf(tsx.path),
  })
}

// tsx path like "src/components/shadcn-space/button/button-01.tsx" -> "../components/shadcn-space/button/button-01.tsx"
function txsRelKey(p) {
  return p.replace(/^src\//, '')
}

// category = the directory segment directly under shadcn-space/ (e.g. "button")
function catOf(p) {
  const m = p.match(/shadcn-space\/([^/]+)/)
  return m ? m[1] : 'misc'
}

mkdirSync(join(ported, 'generated'), { recursive: true })
const out = `// AUTO-GENERATED by scripts/gen-demos.mjs — do not edit.
// Source: shadcnspace registry (MIT), ported under src/web/ported.
export interface DemoEntry {
  // key matches the Vite import.meta.glob('../components/shadcn-space/**/*.tsx') modules
  key: string
  name: string
  title: string
  description: string
  category: string
  categoryTitle: string
}

export const demos: DemoEntry[] = ${JSON.stringify(demos, null, 2)}

export const demosByCategory: Record<string, DemoEntry[]> = {}
for (const d of demos) {
  (demosByCategory[d.category] ??= []).push(d)
}
`
writeFileSync(join(ported, 'generated/demos.ts'), out)
const cats = new Set(demos.map((d) => d.category))
console.log(`wrote ${demos.length} demos in ${cats.size} categories -> generated/demos.ts`)
