/**
 * skill-styles.js — 前端 skill → 视觉样式映射
 *
 * key: "<repoId>::<skillName>"，与 preload.js 扫描出的 skill.id 一致。
 * 未按 key 命中的 skill 会走 REPO_FALLBACK（用仓库配色 + 名称哈希挑质感类）。
 *
 * m : mode   质感类，对应 index.html 里的 .st[data-mode="<m>"] 规则
 * p : [bg, surface, text, muted, accent, accent2]
 * s : [ok, bad, warn]  可选，缺省用通用语义色
 * r : 圆角   b: 毛玻璃模糊 px   f: 字体 sans|mono|serif|hand
 * d : 1 = 深色底
 * tag : 中文风格标签（面板上显示，说明这个 skill 被渲染成什么样子）
 */
export interface SkillStyle {
  /** 质感类，对应 stage.css 的 .aek-stage[data-mode="<m>"] 规则。 */
  m: string
  /** [bg, surface, text, muted, accent, accent2]。 */
  p: string[]
  /** 圆角 px。 */
  r?: string
  /** 字体 sans|mono|serif|hand。 */
  f?: string
  /** 毛玻璃模糊 px（字符串或数字）。 */
  b?: string | number
  /** 1 = 深色底。 */
  d?: number
  /** 可选 [ok, bad, warn] 语义色。 */
  s?: string[]
  tag?: string
}

export interface RepoFallback {
  /** 展示名。 */
  name: string
  /** 仓库主色。 */
  color: string
  /** 一句话说明。 */
  note: string
  /** 缺省质感类池。 */
  modes: string[]
  /**
   * BN round (m06297 ⑤): the skill's upstream repository URL — the
   * gallery's content pane links it next to the usage-doc path so the
   * user can open the author's source. Verified 2026-11-22 against the
   * local clone's origin remote.
   */
  url?: string
}
