/**
 * The live re-skin stage — mirrors the style-gallery reference's Stage IA:
 * name header + spec strip + 4 real-content tabs (overview / components /
 * motion / logs). Everything inside .aek-stage re-skins with the selected
 * spec; the neutral chrome above never does. P16: aek-web's own widgets
 * (self-drawn pills, progress bars, accordion — the reference's ToggleGroup
 * / Progress / Accordion have no aek counterparts).
 *
 * @module @cheezmil/aek-web/src/webui-art-gallery/Stage
 */
import { useMemo, useState } from 'react'
import type { JSX, ReactNode } from 'react'
import { Icon } from '../Icons.tsx'
import { useI18n } from '../i18n.tsx'
import { cssSnippet, normRadius, type GalleryItem, type StageSpec } from './spec.ts'
import { REPO_FALLBACK } from './data/skill-styles.ts'
import { useConsoleFacts } from '../useConsoleFacts.ts'
import { formatDisplayPath, parsePathStyle } from '../paths.ts'
import { PREF_KEYS, usePref } from '../preferences.tsx'
import { copyToClipboard } from '../clipboard.ts'
import { ComponentsPanel, MotionPanel, ChartsPanel, FormsPanel, TablesPanel, OverlaysPanel, FeedbackPanel, NavigationPanel, LayoutPanel } from './StagePanels.tsx'
import { cn } from '@/lib/utils'
import { Button } from '@/components/ui/button'
import { Card, CardHeader, CardTitle, CardDescription, CardContent, CardAction } from '@/components/ui/card'
import { Tooltip, TooltipContent, TooltipProvider, TooltipTrigger } from '@/components/ui/tooltip'

export interface StageCounts {
  styles: number
  skills: number
  repos: number
  kinds: number
  modes: number
}

export interface StageProps {
  item: GalleryItem
  counts: StageCounts
  faved: boolean
  onToggleFav: () => void
  onNotify: (msg: string) => void
}

// BP round (m02138 ⑪): the "overview" tab is retired — the stage opens on
// the charts panel directly; the demo/diagnostics cards and the stats grid
// that lived under it are gone with it.
/** BP round ⑪ (m02138): the tab set follows the shadcn/ui 2026 component
 * families — the four new tabs (overlays / feedback / navigation / layout)
 * each own a showcase panel in StagePanels; the stage still opens on
 * charts. */
const NAVS: { key: string; icon: 'plugins' | 'zap' | 'terminal' | 'chart' | 'form' | 'table' | 'popover' | 'bell' | 'compass' | 'frame' }[] = [
  { key: 'components', icon: 'plugins' },
  { key: 'motion', icon: 'zap' },
  { key: 'charts', icon: 'chart' },
  { key: 'forms', icon: 'form' },
  { key: 'tables', icon: 'table' },
  { key: 'overlays', icon: 'popover' },
  { key: 'feedback', icon: 'bell' },
  { key: 'navigation', icon: 'compass' },
  { key: 'layout', icon: 'frame' },
  { key: 'logs', icon: 'terminal' },
]

/**
 * BN round (m06297 ⑤): the on-disk usage-record file name for one item —
 * the SAME sanitization scripts/aek/seed-art-gallery-usage.mjs uses, so the
 * path we show is byte-for-byte the file the seeder writes.
 */
const sanitizeItem = (id: string): string => id.replace(/::/g, '__').replace(/[:/\\]/g, '_')

/**
 * BQ11 round (m00001 ①): the skill directory name under the host's
 * aek-system-skill/ shelf. It now ships inside the plugin package
 * (skills/aek-ui-gallery/, generated by scripts/aek/seed-art-gallery-usage.mjs)
 * and aeksm seeds it into the hub as aek-system-skill/aek-ui-gallery/ —
 * sibling of aek-usage.
 */
const ART_SHELF = 'aek-ui-gallery'

const SpecItem = ({ k, children }: { k: string; children: ReactNode }): JSX.Element => (
  <div className="flex min-w-0 flex-col gap-1">
    <span className="text-muted-foreground text-2xxs leading-none font-bold uppercase">{k}</span>
    <span className="truncate font-mono text-xs leading-none font-bold">{children}</span>
  </div>
)

export function Stage({ item, counts, faved, onToggleFav, onNotify }: StageProps): JSX.Element {
  const { t } = useI18n()
  const spec = item.spec
  // BP round (m02138 ⑪): first visible tab is the charts panel.
  const [nav, setNav] = useState('charts')
  const [copied, setCopied] = useState(false)

  const swatches = [spec.p[0], spec.p[1], spec.p[3], spec.p[4]]

  // BN round (m06297 ⑤): the provenance facts. The usage-record file path is
  // derived from the host's own console facts (facts.skillPath = the aek-usage
  // shelf under the slot data root) so no absolute path is ever hardcoded —
  // it resolves per machine, exactly where the seeder wrote the .md.
  const { facts } = useConsoleFacts()
  const [pathStyle] = usePref(PREF_KEYS.pathStyle, 'abbreviated', parsePathStyle)
  const repoMeta = item.repoId ? REPO_FALLBACK[item.repoId] : undefined
  const usageDocPath = useMemo((): string | undefined => {
    if (!facts?.skillPath) return undefined
    const shelfRoot = facts.skillPath.replace(/aek-usage$/, '') // keep the trailing slash
    return `${shelfRoot}${ART_SHELF}/${sanitizeItem(item.id)}.md`
  }, [facts?.skillPath, item.id])

  // BO round (m00001 ③): the usage-doc path obeys the global display style
  // (abbreviated `~` / `%USERPROFILE%` vs full); the raw path stays the copy target.
  const usageDocDisplay = usageDocPath !== undefined
    ? formatDisplayPath(usageDocPath, facts?.home, facts?.platform, pathStyle)
    : undefined

  const doCopy = async (): Promise<void> => {
    // BP round (m02138 ①): the header copy button copies the item NAME only —
    // nothing else (the BL-round full usageDoc copy is retired).
    const ok = await copyToClipboard(spec.name)
    if (ok) {
      onNotify(t('art.copied'))
      setCopied(true)
      setTimeout(() => { setCopied(false) }, 1400)
    }
  }

  const [pathCopied, setPathCopied] = useState(false)
  const doCopyPath = async (): Promise<void> => {
    // BP round (m02138 ④): the path line's copy icon copies the RAW
    // usage-record path — the visible text stays abbreviated/full per the
    // global path style, the clipboard always gets the original value.
    if (usageDocPath === undefined) return
    const ok = await copyToClipboard(usageDocPath)
    if (ok) {
      setPathCopied(true)
      setTimeout(() => { setPathCopied(false) }, 1400)
    }
  }

  return (
    <div className="flex flex-col gap-6 px-5 py-6">
      {/* ---- header: name + copy + favorite + status badges ---- */}
      <header className="flex items-start gap-4">
        <div
          className="size-11 flex-none rounded-xl"
          style={{ background: `linear-gradient(135deg, ${spec.p[4]}, ${spec.p[5]})` }}
        />
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-x-2 gap-y-1.5">
            <h1 className="text-xl leading-tight font-bold tracking-tight break-words">{spec.name}</h1>
            <div className="flex flex-none items-center gap-0.5">
              <TooltipProvider delayDuration={250}>
                <Tooltip>
                  <TooltipTrigger asChild>
                    <Button
                      variant="ghost"
                      size="icon-sm"
                      onClick={() => { void doCopy() }}
                      aria-label={t('art.copyName')}
                      className="size-7"
                    >
                      {copied ? <Icon name="check" size={14} className="text-success" /> : <Icon name="copy" size={14} />}
                    </Button>
                  </TooltipTrigger>
                  <TooltipContent>{copied ? t('art.copied') : t('art.copyName')}</TooltipContent>
                </Tooltip>
                <Tooltip>
                  <TooltipTrigger asChild>
                    <Button
                      variant="ghost"
                      size="icon-sm"
                      onClick={onToggleFav}
                      aria-label={faved ? t('art.favRemove') : t('art.favAdd')}
                      className={cn('size-7', faved && 'text-primary hover:text-primary')}
                    >
                      <Icon name="star" size={14} className={cn(faved && 'fill-current')} />
                    </Button>
                  </TooltipTrigger>
                  <TooltipContent>{faved ? t('art.favRemove') : t('art.favAdd')}</TooltipContent>
                </Tooltip>
              </TooltipProvider>
            </div>
            {/* BP round (m02138 ②): the repo chip IS the provenance — the
                dedicated provenance card is gone; the chip links to the repo. */}
            {item.repoName && (
              repoMeta?.url ? (
                <a
                  className="bg-secondary text-secondary-foreground inline-flex items-center gap-1 rounded-full border px-2.5 py-0.5 text-xs font-semibold hover:underline"
                  href={repoMeta.url}
                  target="_blank"
                  rel="noreferrer noopener"
                >
                  {item.repoName}
                  <Icon name="externalLink" size={12} />
                </a>
              ) : (
                <span className="bg-secondary text-secondary-foreground rounded-full border px-2.5 py-0.5 text-xs font-semibold">
                  {item.repoName}
                </span>
              )
            )}
          </div>
          {/* BP round (m02138 ④): the free-text description is replaced by the
              usage-record file path (abbreviated/full per the global path
              style) with its own copy icon — the raw path is the copy target. */}
          {usageDocPath ? (
            <div className="mt-1.5 flex items-center gap-1.5">
              <code className="text-muted-foreground min-w-0 truncate font-mono text-xs" title={usageDocPath}>
                {usageDocDisplay}
              </code>
              <Tooltip>
                <TooltipTrigger asChild>
                  <Button
                    variant="ghost"
                    size="icon-sm"
                    onClick={() => { void doCopyPath() }}
                    aria-label={t('art.copyPath')}
                    className="size-5 shrink-0"
                  >
                    {pathCopied ? <Icon name="check" size={12} className="text-success" /> : <Icon name="copy" size={12} />}
                  </Button>
                </TooltipTrigger>
                <TooltipContent>{t('art.copyPath')}</TooltipContent>
              </Tooltip>
            </div>
          ) : null}
        </div>
      </header>

      {/* ---- spec strip: texture / radius / font / palette ---- */}
      <div className="bg-card grid grid-cols-2 items-center gap-x-6 gap-y-4 rounded-lg border px-5 py-4 sm:grid-cols-4">
        <SpecItem k={t('art.texture')}>{spec.mode}</SpecItem>
        <SpecItem k={t('art.radius')}>{normRadius(spec.radius)}</SpecItem>
        <SpecItem k={t('art.font')}>{spec.font}</SpecItem>
        <div className="flex flex-col gap-1.5">
          <span className="text-muted-foreground text-2xxs leading-none font-bold uppercase">
            {t('art.palette')}
          </span>
          <div className="flex gap-1.5">
            {swatches.map((c, i) => (
              <span key={i} className="size-5 rounded-md border border-border" style={{ background: c }} title={c} />
            ))}
          </div>
        </div>
      </div>

      {/* BP round (m02138 ②): the dedicated provenance card is gone — the
          header's repo chip is the clickable repo link and the header's path
          line is the usage-record file; the card duplicated both. */}

      {/* ---- demo tabs: real content switches, not just the highlight ---- */}
      {/* BP round ⑪: 10 tabs — wrap on narrow stage widths instead of
          overflowing the pill row. */}
      <div className="inline-flex flex-wrap items-center gap-1 rounded-lg bg-secondary p-1">
        {NAVS.map(n => (
          <button
            key={n.key}
            type="button"
            onClick={() => { setNav(n.key) }}
            className={cn(
              'flex items-center gap-1.5 rounded-md px-3 py-1.5 text-xs font-semibold transition-colors',
              nav === n.key ? 'bg-background text-foreground shadow-sm' : 'text-muted-foreground hover:text-foreground',
            )}
          >
            <Icon name={n.icon} size={13} />
            {t(`art.stage.${n.key}`)}
          </button>
        ))}
      </div>

      {nav === 'components' ? (
        <div data-panel="components"><ComponentsPanel /></div>
      ) : nav === 'motion' ? (
        <div data-panel="motion"><MotionPanel /></div>
      ) : nav === 'charts' ? (
        <div data-panel="charts"><ChartsPanel /></div>
      ) : nav === 'forms' ? (
        <div data-panel="forms"><FormsPanel /></div>
      ) : nav === 'tables' ? (
        <div data-panel="tables"><TablesPanel /></div>
      ) : nav === 'overlays' ? (
        <div data-panel="overlays"><OverlaysPanel /></div>
      ) : nav === 'feedback' ? (
        <div data-panel="feedback"><FeedbackPanel /></div>
      ) : nav === 'navigation' ? (
        <div data-panel="navigation"><NavigationPanel /></div>
      ) : nav === 'layout' ? (
        <div data-panel="layout"><LayoutPanel /></div>
      ) : nav === 'logs' ? (
        <div data-panel="logs" className="flex flex-col gap-4"><LogPanel item={item} spec={spec} counts={counts} /></div>
      // BP round (m02138 ⑪): no "overview" fallback — every NAVS key above
      // renders its own panel; the deleted branch carried the stats grid +
      // demo/diagnostics cards + the composition table.
      ) : null}
    </div>
  )
}

/** The "logs" panel: diagnostic stream + re-skin variable snapshot + artifact self-check. */
function LogPanel({ item, spec, counts }: { item: GalleryItem; spec: StageSpec; counts: StageCounts }): JSX.Element {
  const { t, tf } = useI18n()
  const now = new Date().toLocaleTimeString('zh-CN', { hour12: false })
  const isSkill = item.kind === 'skill'
  const logSrc = isSkill ? (item.repoName ?? spec.name) : (item.src ?? item.kindName ?? '')
  const lines: { tag: string; txt: string; tone: 'ok' | 'warn' | 'plain' }[] = [
    { tag: 'boot', txt: t('art.log.boot'), tone: 'ok' },
    { tag: 'data', txt: t('art.log.builtin'), tone: 'warn' },
    {
      tag: 'scan',
      txt: tf('art.log.scan', { src: logSrc, skills: counts.skills, repos: counts.repos, styles: counts.styles }),
      tone: 'ok',
    },
    { tag: 'style', txt: tf('art.log.style', { mode: spec.mode, radius: spec.radius, font: spec.font }), tone: 'ok' },
    {
      tag: 'skin',
      txt: tf('art.log.skin', { n: spec.p.length }),
      tone: 'ok',
    },
    { tag: 'select', txt: tf('art.log.select', { name: spec.name }), tone: 'ok' },
    { tag: 'hint', txt: t('art.log.hint'), tone: 'plain' },
  ]
  return (
    <>
      <Card>
        <CardHeader>
          <div className="min-w-0 flex-1">
            <CardTitle className="text-aek-135">{t('art.logTitle')}</CardTitle>
            <CardDescription>{t('art.logDesc')}</CardDescription>
          </div>
          <CardAction>
            <span className="border-success/30 bg-success/10 text-success rounded-full border px-2.5 py-0.5 text-xs font-semibold">
              {t('art.logOkBadge')}
            </span>
          </CardAction>
        </CardHeader>
        <CardContent>
          <ol className="flex flex-col gap-1.5">
            {lines.map((l, i) => (
              <li key={i} className="bg-background flex items-start gap-3 rounded-lg border px-3.5 py-2.5">
                <span className="text-muted-foreground flex-none font-mono text-aek-11 tabular-nums">{now}</span>
                <span
                  className={cn(
                    'flex-none rounded-md px-1.5 py-px font-mono text-2xxs font-bold',
                    l.tone === 'warn'
                      ? 'bg-destructive/15 text-destructive'
                      : l.tone === 'ok'
                        ? 'bg-success/15 text-success'
                        : 'bg-muted text-muted-foreground',
                  )}
                >
                  {l.tag}
                </span>
                <span className="min-w-0 flex-1 text-xs leading-relaxed">{l.txt}</span>
              </li>
            ))}
          </ol>
        </CardContent>
      </Card>

      <div className="grid grid-cols-2 gap-4">
        <Card>
          <CardHeader>
            <div className="min-w-0 flex-1">
              <CardTitle className="text-aek-135">{t('art.varsTitle')}</CardTitle>
              <CardDescription>{t('art.varsDesc')}</CardDescription>
            </div>
          </CardHeader>
          <CardContent>
            <pre className="bg-background max-h-60 overflow-auto rounded-lg border p-3.5 font-mono text-xs leading-loose">
              {cssSnippet(spec)}
            </pre>
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <div className="min-w-0 flex-1">
              <CardTitle className="text-aek-135">{t('art.checkTitle')}</CardTitle>
              <CardDescription>{t('art.checkDesc')}</CardDescription>
            </div>
          </CardHeader>
          <CardContent>
            <pre className="bg-background max-h-60 overflow-auto rounded-lg border p-3.5 font-mono text-xs leading-loose">
              {[
                t('art.chk1'),
                t('art.chk2'),
                t('art.chk3'),
                tf('art.chk4', { styles: counts.styles, kinds: counts.kinds }),
                t('art.chk5'),
              ].map(line => `[ok] ${line}`).join('\n')}
            </pre>
          </CardContent>
        </Card>
      </div>
    </>
  )
}
