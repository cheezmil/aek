const repoOfSrc = (src: string | undefined): { repoId: string; repoName: string; repoColor: string } | null => {
  // BP round (BP-13): sequential null returns — the `meta ?` truthiness alone
  // did not narrow `repoId` to `string` in the returned object literal.
  if (!src) return null
  const repoId = SRC_REPO_MAP[src]
  // `in` is the runtime guard: REPO_FALLBACK is typed as a plain Record, so a
  // `meta ?` truthiness check alone would not narrow and would look like an
  // unnecessary condition to the linter.
  if (!repoId || !(repoId in REPO_FALLBACK)) return null
  const meta = REPO_FALLBACK[repoId]
  return { repoId, repoName: meta.name, repoColor: meta.color }
}

export function galleryItems(): { styles: GalleryItem[]; skills: GalleryItem[] } {
  const base: GalleryItem[] = AEC_BASE_SPECS.map((spec): GalleryItem => ({
    id: spec.id,
    kind: 'style',
    spec,
    desc: spec.sub,
    kindId: AEC_BASE_KIND.id,
    kindName: AEC_BASE_KIND.name,
    src: AEC_BASE_KIND.src,
    srcColor: AEC_BASE_KIND.color,
    colors: spec.p,
  }))
  const styles: GalleryItem[] = [
    ...base,
    ...ART_STYLES.map((e): GalleryItem => ({
      id: e.id,
      kind: 'style',
      spec: styleSpecOf(e),
      desc: e.desc || `${kindDisplayName(e.kind) ?? e.kind} · ${e.src}`,
      kindId: e.kindId,
      // BP round ⑨: the display name comes from the rename map (the raw
      // generated kind stays in the data, the UI shows the mapped label).
      kindName: kindDisplayName(e.kind) ?? e.kind,
      src: e.src,
      srcColor: e.srcColor,
      colors: e.colors,
      ...(repoOfSrc(e.src) ?? {}),
    })),
  ]
  const skills: GalleryItem[] = skillSpecs().map((spec) => {
    const key = spec.id.slice('skill-'.length)
    const repoId = key.split('::')[0]
    const repoMeta = REPO_FALLBACK[repoId]
    return {
      id: spec.id,
      kind: 'skill',
      spec,
      desc: spec.sub,
      repoId,
      repoName: repoMeta.name,
      repoColor: repoMeta.color,
    }
  })
  return { styles, skills }
}

