/**
 * BO round (m00001 ⑪): favorites are groupable — each group is a named
 * list of spec ids and groups get full CRUD (create / rename / delete /
 * read). An item counts as faved when it belongs to at least one group.
 * Storage: FAV_GROUPS_KEY holds `{ v: 1, groups }`; the legacy FAV_KEY
 * flat array is migrated into one default group (empty id + name) on
 * first read, then cleared.
 */
export interface FavGroup {
  id: string
  /** '' marks the default group — rendered with the localized default label. */
  name: string
  items: string[]
}

const FAV_GROUPS_KEY = 'aek-art-fav-groups'

const isStr = (x: unknown): x is string => typeof x === 'string'

const DEFAULT_GROUP = (): FavGroup => ({ id: '', name: '', items: [] })

/** The persisted favorite groups; broken storage degrades to one empty default. */
export const readFavGroups = (): FavGroup[] => {
  let groups: FavGroup[] | null = null
  try {
    const raw = window.localStorage.getItem(FAV_GROUPS_KEY)
    if (raw) {
      const doc = JSON.parse(raw) as { groups?: unknown }
      if (Array.isArray(doc.groups)) {
        groups = doc.groups
          .filter((g): g is Record<string, unknown> => !!g && typeof g === 'object')
          .map(g => ({
            id: isStr(g.id) ? g.id : '',
            name: isStr(g.name) ? g.name : '',
            items: Array.isArray(g.items) ? [...new Set(g.items.filter(isStr))] : [],
          }))
      }
    }
    if (!groups) {
      // Legacy migration: a flat string[] of faved ids → one default group.
      const legacy = window.localStorage.getItem(FAV_KEY)
      const list = legacy ? (JSON.parse(legacy) as unknown[]) : []
      const ids = [...new Set(list.filter(isStr))]
      groups = [{ id: '', name: '', items: ids }]
    }
  } catch {
    groups = [DEFAULT_GROUP()]
  }
  if (!groups.length) groups = [DEFAULT_GROUP()]
  return groups
}

/** Persist the groups; also retires the legacy flat key. Storage refusals degrade to in-memory. */
export const writeFavGroups = (groups: FavGroup[]): void => {
  try {
    window.localStorage.setItem(FAV_GROUPS_KEY, JSON.stringify({ v: 1, groups }))
    window.localStorage.removeItem(FAV_KEY)
  } catch {
    /* private-mode storage may refuse; groups stay in-memory */
  }
}

/** The union of every group's items — the "is faved" set all views use. */
export const favsOfGroups = (groups: FavGroup[]): ReadonlySet<string> => {
  const s = new Set<string>()
  for (const g of groups) for (const id of g.items) s.add(id)
  return s
}

/** The persisted favorites (union over all groups); broken storage degrades to none. */
export const readFavorites = (): ReadonlySet<string> => favsOfGroups(readFavGroups())

/**
 * BP round (m02138 ⑦): light/dark tone classification for the gallery pools.
 * The automatic tone is the WCAG relative luminance of the spec's background
 * slot; when the classification is wrong the user can click-mark an item, and
 * the override map (TONE_OVERRIDES_KEY, shimmed to the host data root) wins.
 */
export type Tone = 'light' | 'dark'

const TONE_OVERRIDES_KEY = 'aek-art-tone-overrides'

/**
 * WCAG relative luminance of a hex color. Returns -1 for unparseable input so
 * callers can distinguish "the program cannot classify this background" from
 * "a measured, confident luminance".
 */
const luminanceOf = (hex: string | undefined): number => {
  const m = /^#?([0-9a-f]{6})$/i.exec((hex ?? '').trim())
  if (!m) return -1
  const n = parseInt(m[1], 16)
  const chan = (v: number): number => {
    const c = v / 255
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  }
  return 0.2126 * chan((n >> 16) & 255) + 0.7152 * chan((n >> 8) & 255) + 0.0722 * chan(n & 255)
}

/**
 * The gray band around the 0.45 light/dark threshold where the automatic
 * classification is effectively a coin flip — these are the backgrounds the
 * program genuinely cannot place with confidence. The settled tone still
 * lands on one side (see autoToneOf), but the item also belongs to the
 * 程序无法分类 review queue until the user marks it.
 */
const TONE_UNCERTAIN_LO = 0.35
const TONE_UNCERTAIN_HI = 0.55

/** The automatic tone: the background slot's luminance at a 0.45 threshold. */
export const autoToneOf = (item: GalleryItem): Tone => {
  const bg = item.spec.p[0] ?? item.colors?.[0]
  const lum = luminanceOf(bg)
  // Unparseable background: keep the legacy settled-tone default (light) —
  // uncertainty is signalled separately by isUncertainOf.
  if (lum < 0) return 'light'
  return lum >= 0.45 ? 'light' : 'dark'
}

export const readToneOverrides = (): Record<string, Tone> => {
  try {
    const raw = window.localStorage.getItem(TONE_OVERRIDES_KEY)
    if (!raw) return {}
    const doc = JSON.parse(raw) as unknown
    if (!doc || typeof doc !== 'object' || Array.isArray(doc)) return {}
    const out: Record<string, Tone> = {}
    // Cast away `object`: Object.entries on a bare `object` yields `any`
    // values, which the no-unsafe-assignment rule rejects.
    for (const [k, v] of Object.entries(doc as Record<string, unknown>)) {
      if (v === 'light' || v === 'dark') out[k] = v
    }
    return out
  } catch {
    return {}
  }
}

/** Set (or clear with null) the user's tone mark for one item. */
export const writeToneOverride = (id: string, tone: Tone | null): void => {
  try {
    // Rebuild the map instead of `delete all[id]` — the no-dynamic-delete
    // rule rejects dynamically-computed property deletions.
    const all = readToneOverrides()
    const next: Record<string, Tone> = {}
    for (const [k, v] of Object.entries(all)) if (k !== id) next[k] = v
    if (tone !== null) next[id] = tone
    window.localStorage.setItem(TONE_OVERRIDES_KEY, JSON.stringify(next))
  } catch {
    /* private-mode storage may refuse; the override stays in-memory */
  }
}

/** The effective tone: a user mark beats the automatic classification. */
export const effectiveToneOf = (item: GalleryItem, overrides: Record<string, Tone>): Tone =>
  overrides[item.id] ?? autoToneOf(item)

/**
 * BQ4 round (m00001): the sidebar chip row is now a 4-way pool selector —
 * the user banned the 按-Skill top pill and asked the chip container to hold
 * ONLY 收藏 / 浅色 / 深色 / 程序无法分类.
 *
 * BQ9 round (m04182): 程序无法分类 was originally "every item the user has
 * not marked yet", which collapsed to the WHOLE set (浅色+深色 = 405) and read
 * as a contradiction. It now means "the program could NOT confidently place
 * this background" — an unparseable bg, or a luminance inside the gray band
 * [TONE_UNCERTAIN_LO, TONE_UNCERTAIN_HI] around the 0.45 threshold. Those
 * items still land in 浅色/深色 via their settled tone (autoToneOf / a user
 * mark), but they ALSO sit in the 程序无法分类 review queue until the user
 * marks one. The switcher prompts the user to mark the current one 浅色/深色,
 * and the mark (a tone override) is persisted, so the item leaves the queue.
 */
export type ViewSel = 'fav' | 'light' | 'dark' | 'unclass'

/**
 * BQ9 round (m04182): the program could NOT confidently classify this item's
 * background — the bg is unparseable, or its luminance falls in the gray band
 * around the 0.45 light/dark threshold where the auto guess is a coin flip.
 */
export const isUncertainAutoOf = (item: GalleryItem): boolean => {
  const lum = luminanceOf(item.spec.p[0] ?? item.colors?.[0])
  if (lum < 0) return true
  return lum >= TONE_UNCERTAIN_LO && lum <= TONE_UNCERTAIN_HI
}

/**
 * BQ9 round (m04182): membership in the 程序无法分类 review queue = the
 * automatic classification is uncertain AND the user has not yet marked it.
 * (Replaces the old "every unmarked item" pool, which equaled the whole
 * set and contradicted the 浅色/深色 counts.)
 */
export const inUnclassQueue = (item: GalleryItem, overrides: Record<string, Tone>): boolean =>
  isUncertainAutoOf(item) && !(item.id in overrides)

/**
 * BQ5 round: the active chip pool (收藏 / 浅色 / 深色 / 程序无法分类) is
 * remembered across restarts — one-line string key, transparently redirected
 * to the host yml by the host-storage shim (never a browser profile).
 */
const VIEWSEL_KEY = 'aek-art-viewsel'

/** The persisted active chip pool; broken storage → null. */
export const readViewSel = (): ViewSel | null => {
  try {
    const raw = window.localStorage.getItem(VIEWSEL_KEY)
    if (raw === 'fav' || raw === 'light' || raw === 'dark' || raw === 'unclass') return raw
    return null
  } catch {
    return null
  }
}

/** Persist the active chip pool; storage refusals degrade to in-memory. */
export const writeViewSel = (v: ViewSel): void => {
  try {
    window.localStorage.setItem(VIEWSEL_KEY, v)
  } catch {
    /* private-mode storage may refuse; the selection stays in-memory */
  }
}
