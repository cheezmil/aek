#!/usr/bin/env node
/**
 * gen-art-styles.mjs — one-shot data generator for the aek-web art gallery.
 *
 * The style-gallery reference app gets its 346-entry style library from a
 * Node preload bridge that scans a local frontend-skills checkout (CSV
 * catalog tables + reference md directories + SKILL.md inline styles).
 * aek-web is a pure webui (P15: no Node bridge), so this script runs that
 * same scanner ONCE and bundles the result as static data into
 * apps/aek-web/src/webui-art-gallery/data/all-styles.ts.
 *
 * Usage:
 *   node scripts/aek/gen-art-styles.mjs [options]
 *     --gallery <dir>   style-gallery reference repo (default: ~/MyDurio/my-ztools-plugins/style-gallery)
 *     --root <dir>      frontend-skills data source (default: ~/MyDurio/frontend-skills, or $FRONTEND_SKILLS_DIR)
 *     --out <file>      output data file (default: the aek-web all-styles.ts path)
 *
 * Re-run after the source catalogs change; the generated file records the
 * source root + totals in its header. No argument-less invocation needed:
 * the script only writes when you run it explicitly.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import os from 'node:os'
import path from 'node:path'

const args = process.argv.slice(2)
const opt = (name, fallback) => {
  const i = args.indexOf(`--${name}`)
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback
}
const HOME = os.homedir()
const galleryDir = opt('gallery', path.join(HOME, 'MyDurio/my-ztools-plugins/style-gallery'))
const rootDir = opt('root', process.env.FRONTEND_SKILLS_DIR || path.join(HOME, 'MyDurio/frontend-skills'))
const outPath = opt('out', path.join(import.meta.dirname, '../../apps/aek-web/src/webui-art-gallery/data/all-styles.ts'))

const preload = path.join(galleryDir, 'preload.js')
if (!existsSync(preload)) {
  console.error(`gen-art-styles: reference preload not found: ${preload}`)
  process.exit(2)
}
if (!existsSync(rootDir)) {
  console.error(`gen-art-styles: frontend-skills root not found: ${rootDir}`)
  process.exit(2)
}

// Run the reference scanner with a window shim (it assigns window.sgNative).
process.env.FRONTEND_SKILLS_DIR = rootDir
globalThis.window = {}
// preload.js is CommonJS-shaped; load its text and eval it in a function
// scope with a real require (created for this ESM script) + process/window,
// so it assigns window.sgNative.
const text = readFileSync(preload, 'utf8')
const requireShim = createRequire(import.meta.url)
const fn = new Function('require', 'process', 'window', 'console', text)
fn(requireShim, process, globalThis.window, console)
const N = globalThis.window.sgNative
if (!N || !N.ok || typeof N.scanStyles !== 'function') {
  console.error(`gen-art-styles: reference scanner unavailable (err: ${N?.err ?? 'no sgNative'})`)
  process.exit(3)
}

const result = N.scanStyles(true)
const styles = result.styles
const kinds = result.kinds
console.log(`gen-art-styles: ${styles.length} styles across ${kinds.length} kinds (colored ${result.totals.colored})`)
for (const k of kinds) console.log(`  ${k.id.padEnd(8)} ${String(k.count).padStart(3)}  ${k.kind} · ${k.src}`)
if (result.warnings?.length) console.warn('warnings:', result.warnings)

// Slim field set: everything the aek Stage/sidebar/compare UI renders.
// (meta/file/csvRow are reference-app file-open affordances; aek has none.)
const slim = styles.map((s) => ({
  id: s.id,
  kindId: s.kindId,
  kind: s.kind,
  src: s.src,
  srcColor: s.srcColor,
  name: s.name,
  desc: s.desc || '',
  colors: (s.colors || []).slice(0, 5),
  mode: s.mode,
  radius: s.radius ?? null,
  font: s.font ?? null,
  blur: s.blur ?? null,
}))

const body = [
  '/**',
  ' * AUTO-GENERATED by scripts/aek/gen-art-styles.mjs — do not edit by hand.',
  ` * source root: $FRONTEND_SKILLS_DIR or --root argument (basename ${path.basename(rootDir)})`,
  ` * scanned: ${new Date().toISOString()}`,
  ` * totals: ${styles.length} styles · ${kinds.length} kinds · ${result.totals.colored} colored`,
  ' * Re-run the generator after the upstream catalogs change.',
  ' */',
  '',
  'export interface ArtStyleEntry {',
  '  id: string',
  "  kindId: string",
  '  kind: string',
  '  src: string',
  '  srcColor: string',
  '  name: string',
  '  desc: string',
  '  /** up to 5 [bg, surface, text, accent, accent2] hex values (may be empty). */',
  '  colors: string[]',
  '  mode: string',
  '  radius: string | null',
  '  font: string | null',
  '  blur: number | null',
  '}',
  '',
  'export interface ArtStyleKind {',
  '  id: string',
  '  name: string',
  '  src: string',
  '  color: string',
  '  count: number',
  '}',
  '',
].join('\n')

// aek house style: single quotes + trailing commas on multi-line literals
// (JSON.stringify emits double quotes and no trailing commas — 134 lint hits).
function q(s) {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`
}
function identKey(k) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : q(k)
}
function fmt(v, ind) {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'string') return q(v)
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (Array.isArray(v)) {
    if (!v.length) return '[]'
    const inner = `${ind}  `
    return `[\n${v.map(x => `${inner}${fmt(x, inner)}`).join(',\n')},\n${ind}]`
  }
  const entries = Object.entries(v)
  if (!entries.length) return '{}'
  const inner = `${ind}  `
  return `{\n${entries.map(([k, x]) => `${inner}${identKey(k)}: ${fmt(x, inner)}`).join(',\n')},\n${ind}}`
}
const kindsData = kinds.map(k => ({ id: k.id, name: k.name, src: k.src, color: k.color, count: k.count }))

const fileBody = `${body}export const ART_STYLE_KINDS: ArtStyleKind[] = ${fmt(kindsData, '')}\n\nexport const ART_STYLES: ArtStyleEntry[] = ${fmt(slim, '')}\n`
writeFileSync(outPath, fileBody)
console.log(`gen-art-styles: wrote ${outPath} (${(Buffer.byteLength(fileBody) / 1024).toFixed(0)} KB)`)
