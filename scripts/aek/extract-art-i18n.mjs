// BQ10: extract the art.* i18n dict (ZH + EN) out of the host aek-web i18n.tsx
// and emit a self-contained module for the SPA. The SPA is OUT of the i18n gate
// scope (src/web, not src/client), so it owns its own copy of the art.* copy.
//
// NOTE (post-BQ10): the SPA now OWNS the art.* copy — art-i18n.ts under
// packages/aek/coraek-plugins/aek-ui-gallery/src/web/ is the source of truth,
// and the host i18n.tsx no longer defines art.* keys. So this extractor will
// find 0 keys and REFUSES to overwrite the SPA dict (guard below). To add keys,
// edit the SPA's art-i18n.ts directly; keep host + SPA in sync manually.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// script lives at <repo>/scripts/aek/ → repo root is two levels up
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const src = readFileSync(join(root, 'apps/aek-web/src/i18n.tsx'), 'utf8')

function blockKeys(src, startMarker, endMarker) {
  const a = src.indexOf(startMarker)
  const b = src.indexOf(endMarker, a)
  if (a < 0 || b < 0) throw new Error(`marker not found: ${startMarker}/${endMarker}`)
  const body = src.slice(a, b)
  const m = {}
  // group 1 = key (art.xxx), group 2 = single-line string value
  const re = /^\s*('(art\.[^']+)'\s*:\s*'(.*?)')\s*,?\s*$/gm
  let hit
  while ((hit = re.exec(body))) {
    const key = hit[2]
    const val = hit[3]
    m[key] = val
  }
  return m
}
// ZH art.* lives in the ZH object; EN art.* in the EN object.
const zh = blockKeys(src, "const ZH:", "const EN:")
const en = blockKeys(src, "const EN:", "const DICTS:")
const keysZ = Object.keys(zh).length, keysE = Object.keys(en).length
console.log(`extracted art.* -> ZH=${keysZ} EN=${keysE}`)
// Post-BQ10 the SPA owns the art.* copy and the host i18n has no art.* keys.
// A 0-key extraction would clobber the live SPA dict — abort instead.
if (keysZ === 0 || keysE === 0) {
  console.error(`REFUSING to overwrite the SPA art-i18n.ts with an empty dict (ZH=${keysZ} EN=${keysE}). The SPA now owns the art.* copy; edit its art-i18n.ts directly.`)
  process.exit(1)
}

const out = `// BQ10: art.* i18n dict extracted from aek-web (host i18n.tsx). The SPA owns
// its own copy of the art-gallery copy; the host i18n drops these keys.
// Generated by scripts/aek/extract-art-i18n.mjs — re-run after adding keys.
export type ArtLocale = 'zh-CN' | 'en-US'
export type ArtDict = Record<string, string>
export const ART_I18N: Record<ArtLocale, ArtDict> = {
  'zh-CN': ${JSON.stringify(zh, null, 2).replace(/\n/g, '\n  ')},
  'en-US': ${JSON.stringify(en, null, 2).replace(/\n/g, '\n  ')},
}
`
const dest = join(root, 'packages/aek/coraek-plugins/aek-ui-gallery/src/web/art-i18n.ts')
writeFileSync(dest, out)
console.log(`wrote ${dest} (${Object.keys(zh).length} keys)`)
